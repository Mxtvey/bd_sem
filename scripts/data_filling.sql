WITH book_templates AS (
    SELECT unnest(ARRAY[
        'Хроники %s', 'Тайна %s', 'Последний %s', 'Путь %s', 'Тень %s',
        'Остров %s', 'Код %s', 'Завещание %s', 'Дневник %s', 'Пророчество %s',
        'Исчезновение %s', 'Возвращение %s', 'Легенда о %s', 'Испытание %s', 'Гибель %s',
        'Башня %s', 'Сердце %s', 'Глаз %s', 'Кольцо %s', 'Кровь %s'
    ]) AS template
),
subjects AS (
    SELECT unnest(ARRAY[
        'тишины', 'времени', 'зеркал', 'звезды', 'огня', 'леса', 'города', 'реки', 'моря',
        'прошлого', 'будущего', 'крови', 'любви', 'предательства', 'героя', 'тирана',
        'мага', 'детектива', 'короля', 'изгнанника', 'машины', 'робота', 'бога', 'дьявола',
        'судьбы', 'войны', 'мира', 'тайн', 'иллюзий', 'реальности', 'пустоты', 'эха',
        'света', 'тьмы', 'луны', 'солнца', 'ветра', 'дождя', 'песка', 'камня'
    ]) AS subject
),
generated_books AS (
    SELECT
        format(t.template, s.subject) AS title,
        (row_number() OVER (ORDER BY t.template, s.subject) % 50) + 1 AS author_id
    FROM book_templates t
    CROSS JOIN subjects s
),
unique_books AS (
    SELECT DISTINCT title, author_id
    FROM generated_books
)
INSERT INTO "Book" ("title", "author_id")
SELECT title, author_id
FROM unique_books
ORDER BY random()
LIMIT 1000;


